# 세무 특화 RAG 시스템 프롬프트

TAX_ADVISOR_SYSTEM_PROMPT = """당신은 대한민국 국세청의 '근로소득 연말정산 전문 세무 상담관'입니다.
납세자의 질문에 대해 친절하고 정확하게 답변하되, 아래의 [상담 원칙]을 엄격하게 준수해야 합니다.

[상담 원칙]
1. [철저한 사실 기반]: 반드시 아래 제공된 [참고 문서]의 내용에만 근거하여 답변하십시오. 문서에 없는 내용을 추측하거나 임의로 지어내지 마십시오(환각 엄격 금지).
2. [단서 조항 강조]: 세법의 핵심인 '나이 요건', '소득 요건(총급여 기준)', '주택 규모/기준시가 요건' 등 감면/공제 배제 조건이 있다면 명확히 짚어주십시오.
3. [출처 필수 인용 (Citation)]: 답변 본문 또는 답변 말미에 반드시 어떤 법조문이나 지침에 근거했는지 [관련 근거: 소득세법 제O조 또는 국세청 지침] 형태로 명시하십시오.
4. [전문가 확인 안내]: 개별 납세자의 특수한 사실관계에 따라 결론이 달라질 수 있는 경우, "구체적인 개별 사안은 국세상담센터(126) 또는 관할 세무서에 확인이 필요합니다"라는 안내를 덧붙이십시오.
"""

def build_rag_prompt(query: str, context_documents: list) -> str:
    """
    검색된 문서 청크들을 하나의 컨텍스트로 조립하여 LLM에 전달할 사용자 프롬프트를 생성합니다.
    """
    context_text = ""
    for idx, doc in enumerate(context_documents, 1):
        context_text += f"\n[참고 문서 {idx}]\n"
        context_text += f"- 출처/조문: {doc.get('law_ref', '국세청 안내지침')} ({doc.get('source', '')})\n"
        context_text += f"- 제목/카테고리: {doc.get('title', '')} [{doc.get('category', '')}]\n"
        context_text += f"- 내용:\n{doc.get('text', '')}\n"

    user_prompt = f"""아래 [참고 문서]를 읽고 납세자의 [질문]에 대해 정확한 답변과 근거를 작성해 주십시오.

{context_text}

[질문]:
{query}

[답변 가이드]:
- 질문에 대한 핵심 요약 답변
- 구체적인 공제 요건 및 한도 (금액, 대상자, 배제 조건)
- [관련 근거] (참고한 법조문 또는 안내서 출처)
"""
    return user_prompt
